import java.util.Scanner;
public class pgm2switch {
 public static void main(String[] args) {
     Scanner scan = new Scanner (System.in);
int n = scan.nextInt();
switch (n){
    case 1 : System.err.println("one");
    break;
    case 2 : System.err.println("two");
    break;
    case 3 : System.err.println("three");
    break;
    case 4 : System.err.println("four");
    break;
    case 5 : System.err.println("five");
    break;
    case 6 : System.err.println("6");
    break;
    case 7 : System.err.println("7");
    break;
    case 8 : System.err.println("8");
    break;
    case 9 : System.err.println("9");
    break;
    case 10 : System.err.println("10");
    break;
    default : System.err.println("Invalid");
    break;
        }
 }
}
